FACTION_NAMES = {"democratic": ("DEMOCRATIC", 6), "communism": ("COMMUNIST", 5),
                 "fascism": ("FASCIST", 5), "neutrality": ("NONALIGNED", 5)}
# Second group of the default 70/30 split when a faction lists no popularities.
DEFAULT_SPLIT_SECOND = {"neutrality": "democratic"}


def subtype(group: str) -> str:
    return f"{group}_subtype"


def ideology_file() -> str:
    out = ["# Generated by tools/ideologies.py from data/ideologies.yaml.", "ideologies = {"]
    for gid, g in geo.load_ideologies().items():
        out.append(f"\t{gid} = {{\n\t\ttypes = {{\n\t\t\t{subtype(gid)} = {{\n\t\t\t}}")
        for t in g.get("legacy", ()):
            # Kept so vanilla characters and scripts naming it stay valid; never given to random leaders.
            out.append(f"\t\t\t{t} = {{\n\t\t\t\tcan_be_randomly_selected = no\n\t\t\t}}")
        key, n = FACTION_NAMES[g["template"]]
        names = "\n".join(f'\t\t\t"FACTION_NAME_{key}_{i}"' for i in range(1, n + 1))
        r, gr, b = g["colour"]
        out.append(f"\t\t}}\n\t\tdynamic_faction_names = {{\n{names}\n\t\t}}\n\t\tcolor = {{ {r} {gr} {b} }}")
        out.append(TEMPLATES[g["template"]] + "\t}")
    out.append("}")
    return "\n".join(out) + "\n"


def gfx_file() -> str:
    sprites = "".join(f'\tspriteType = {{\n\t\tname = "GFX_ideology_{gid}_group"\n'
                      f'\t\ttexturefile = "gfx/interface/ideologies/{g["icon"]}.dds"\n\t}}\n'
                      for gid, g in geo.load_ideologies().items()
                      if gid not in FACTION_NAMES)  # vanilla keeps the four reused ids' sprites
    return f"spriteTypes = {{\n{sprites}}}\n"


# Tags the spec dropped (RDN Reindeer Nation easter egg; tag is to be reused for the WFR breakaway).
DROPPED_TAGS = {"RDN"}


def leader_id(tag: str) -> str:
    return f"{tag}_leader"


def portrait_path(slug: str) -> str:
    return f"gfx/leaders/nwc/{slug}.png"


def characters_file() -> str:
    out = ["characters = {"]
    for tag, f in geo.load_factions().items():
        if f.leader:
            pic = (f"\t\tportraits = {{\n\t\t\tcivilian = {{\n\t\t\t\tlarge = \"{portrait_path(f.portrait)}\"\n"
                   f"\t\t\t}}\n\t\t}}\n" if f.portrait else "")
            out.append(f"\t{leader_id(tag)} = {{\n\t\tname = {leader_id(tag)}\n{pic}\t\tcountry_leader = {{\n"
                       f"\t\t\tideology = {subtype(f.ideology)}\n\t\t\texpire = \"2100.1.1\"\n\t\t}}\n\t}}")
    out.append("}")
    return "\n".join(out) + "\n"


def popularities(f: geo.Faction) -> dict[str, int]:
    if f.popularities:
        return dict(f.popularities)
    other = DEFAULT_SPLIT_SECOND.get(f.ideology, "neutrality")
    return {f.ideology: 70, other: 30}


def localisation() -> str:
    def q(s):
        return s.replace('"', "'")

    ideos = geo.load_ideologies()
    rows = ["l_english:"]
    for gid, g in ideos.items():
        rows += [f' {gid}:0 "{q(g["adjective"])}"', f' {gid}_noun:0 "{q(g["name"])}"',
                 f' {gid}_desc:0 "{q(g["desc"])}"', f' {subtype(gid)}:0 "{q(g["name"])}"',
                 f' {subtype(gid)}_desc:0 "{q(g["desc"])}"',
                 f' {gid}_drift:0 "Daily {q(g["name"])} Support"',
                 f' {gid}_acceptance:0 "Acceptance of {q(g["adjective"])} Diplomacy"']
    for tag, f in geo.load_factions().items():
        if tag in DROPPED_TAGS:
            continue
        over = {g: (s, l) for g, s, l in f.parties}
        for gid, g in ideos.items():
            s, l = over.get(gid, (g["name"], f"{f.adjective} {g['name']}"))
            rows += [f' {tag}_{gid}_party:0 "{q(s)}"', f' {tag}_{gid}_party_long:0 "{q(l)}"']
        if f.leader:
            rows.append(f' {leader_id(tag)}:0 "{q(f.leader)}"')
    return "\n".join(rows) + "\n"


def write_all(mod: Path) -> None:
    files = {"common/ideologies/00_ideologies.txt": ideology_file(),
             "common/characters/nwc_leaders.txt": characters_file(),
             "interface/nwc_ideologies.gfx": gfx_file()}
    for rel, text in files.items():
        p = mod / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    # In replace/ so the four reused vanilla ids' names override vanilla's.
    d = mod / "localisation" / "english" / "replace"
    d.mkdir(parents=True, exist_ok=True)
    (d / "nwc_ideologies_l_english.yml").write_bytes(b"\xef\xbb\xbf" + localisation().encode("utf-8"))
